def run_dashboard_server(root: str | Path, *, host: str = "127.0.0.1", port: int = 8765):
    """Serve the dashboard with the current FastAPI backend.

    Kept as a compatibility import path for callers that previously imported
    ``vla_lens.server.run_dashboard_server``.
    """

    from vla_lens.server.fastapi_app import run_dashboard_fastapi_server

    return run_dashboard_fastapi_server(root, host=host, port=port)




